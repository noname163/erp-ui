function buildDailyWorks(monthStart: string): PrepArtifact['dailyWorks'] {
  const dates = workDates(monthStart)
  return [
    { workingDate: dates.normal1, workType: 'NORMAL', startTime: '09:00', endTime: '17:00', quantity: 8, otTime: 0 },
    { workingDate: dates.late, workType: 'NORMAL', startTime: '09:30', endTime: '17:00', quantity: 7.5, otTime: 0 },
    { workingDate: dates.ot, workType: 'NORMAL', startTime: '09:00', endTime: '19:00', quantity: 10, otTime: 2 },
    { workingDate: dates.pto, workType: 'PTO_PAID', startTime: '09:00', endTime: '17:00', quantity: 8, usedPto: true, otTime: 0 },
    { workingDate: dates.weekend, workType: 'WEEKEND_WORK', startTime: '09:00', endTime: '17:00', quantity: 8, otTime: 0 },
    { workingDate: dates.holiday, workType: 'HOLIDAY_WORK', startTime: '09:00', endTime: '17:00', quantity: 8, otTime: 0 },
  ]
}

function buildCalendarDates(start: string, end: string) {
  const result: Array<{ calDate: string; dayType: string; note: string }> = []
  const holiday = workDates(start).holiday
  for (let date = new Date(`${start}T00:00:00`); toIso(date) <= end; date.setDate(date.getDate() + 1)) {
    const iso = toIso(date)
    let dayType = [0, 6].includes(date.getDay()) ? 'WEEKEND' : 'NORMAL'
    if (iso === holiday) dayType = 'HOLIDAY'
    result.push({ calDate: iso, dayType, note: `QA ${dayType}` })
  }
  return result
}

function workDates(monthStart: string) {
  const normalDates: string[] = []
  const weekendDates: string[] = []
  for (let date = new Date(`${monthStart}T00:00:00`); normalDates.length < 6 || weekendDates.length < 1; date.setDate(date.getDate() + 1)) {
    const iso = toIso(date)
    if ([0, 6].includes(date.getDay())) weekendDates.push(iso)
    else normalDates.push(iso)
  }
  return {
    normal1: normalDates[0],
    late: normalDates[1],
    ot: normalDates[2],
    pto: normalDates[3],
    holiday: normalDates[4],
    weekend: weekendDates[0],
  }
}

function monthRange(month: string) {
  const [year, monthNumber] = month.split('-').map(Number)
  const start = new Date(year, monthNumber - 1, 1)
  const end = new Date(year, monthNumber, 0)
  return { start: toIso(start), end: toIso(end) }
}

function toIso(date: Date) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

function makeRunId() {
  return Date.now().toString(36).toUpperCase()
}

function uniquePhone() {
  return `+849${String(Date.now()).slice(-8)}`
}

function writePrepReport(artifact: PrepArtifact) {
  const dir = path.resolve(process.cwd(), 'e2e-report/payroll-data-prep')
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'latest.json'), JSON.stringify(artifact, null, 2), 'utf8')
  fs.writeFileSync(path.join(dir, 'latest.md'), renderMarkdown(artifact), 'utf8')
}


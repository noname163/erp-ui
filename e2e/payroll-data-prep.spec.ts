type PrepArtifact = {
  runId: string
  payrollMonth: string
  employee: {
    code: string
    email: string
    password: string
    fullName: string
  }
  department: {
    code: string
    name: string
  }
  salaryComponents: Array<{
    code: string
    name: string
    calculateMethod: string
  }>
  salaryTemplate: {
    code: string
    name: string
    totalAmount: string
  }
  employeeSalary: {
    code: string
    totalAmount: string
    salaryBasisType: string
  }
  payrollPolicy: {
    code: string
    name: string
    standardQuantityPerDay: number
  }
  dailyWorks: Array<{
    workingDate: string
    workType: string
    startTime: string
    endTime: string
    quantity: number
    usedPto?: boolean
    otTime?: number
  }>
  optionalRunPayrollCommand: string
}

test.describe('payroll data preparation @prep-payroll', () => {
  test('creates full payroll-ready employee dataset', async () => {
    const api = await authenticatedApi(requireAccount('HUMAN_RESOURCES'))
    const runId = makeRunId()
    const payrollMonth = process.env.E2E_PREP_PAYROLL_MONTH ?? '2026-09'
    const period = monthRange(payrollMonth)
    const employeeEmail = `qa.payroll.${runId.toLowerCase()}@example.com`
    const employeeFullName = `Payroll ${runId}`
    const dailyWorks = buildDailyWorks(period.start)

    try {
      await createCompanyCalendarIfPossible(api, runId, period)

      const departmentName = `QA Payroll Dept ${runId}`
      const departmentCode = await createDepartment(api, {
        name: departmentName,
        code: `DPT-QA-${runId}`,
        hrEmail: requireAccount('HUMAN_RESOURCES').email,
      })

      const employee = await createEmployee(api, {
        runId,
        hrEmail: requireAccount('HUMAN_RESOURCES').email,
        email: employeeEmail,
        firstName: 'Payroll',
        lastName: runId,
        departmentCode,
      })

      if (dbPatchEnabled()) {
        patchEmployeePassword(employeeEmail)
      }

      const salaryComponents = await createSalaryComponents(api, runId)
      const baseComponent = salaryComponents[0]
      const allowanceComponent = salaryComponents[1]

      const salaryTemplate = await createSalaryTemplate(api, runId, period, baseComponent.code, allowanceComponent.code)
      const employeeSalary = await createEmployeeSalary(
        api,
        period,
        employee.code,
        salaryTemplate.code,
        baseComponent.code,
        allowanceComponent.code,
      )

      const payrollPolicy = await createPayrollPolicy(api, runId, period)
      if (dbPatchEnabled()) {
        insertDefaultPayRates(payrollPolicy.code, `PRATE-${runId}`, period.start, period.end)
      }

      await assignPayrollPolicy(api, employee.code, payrollPolicy.code, period)
      await createDailyWorks(api, employee.code, dailyWorks)

      const artifact: PrepArtifact = {
        runId,
        payrollMonth,
        employee: {
          code: employee.code,
          email: employeeEmail,
          password: dbPatchEnabled() ? TEST_EMPLOYEE_PASSWORD : 'Generated by backend email flow',
          fullName: employeeFullName,
        },
        department: {
          code: departmentCode,
          name: departmentName,
        },
        salaryComponents,
        salaryTemplate,
        employeeSalary,
        payrollPolicy,
        dailyWorks,
        optionalRunPayrollCommand:
          `POST /api/payroll-runs?runDate=${payrollMonth} as HR, then open /payroll/results for the returned payrollRunCode`,
      }

      writePrepReport(artifact)
      expect(artifact.employee.code).toBeTruthy()
      expect(artifact.payrollPolicy.code).toBeTruthy()
      expect(artifact.employeeSalary.code).toBeTruthy()
    } finally {
      await disposeApi(api)
    }
  })
})

async function createCompanyCalendarIfPossible(api: any, runId: string, period: { start: string; end: string }) {
  const response = await api.post('/api/company-calendars', {
    data: {
      name: `QA Payroll Calendar ${runId}`,
      effectiveFrom: period.start,
      effectiveTo: period.end,
      region: 'VN',
      timeZone: 'Asia/Ho_Chi_Minh',
      note: `QA payroll prep calendar ${runId}`,
      dates: buildCalendarDates(period.start, period.end),
    },
  })

  if (response.status() === 401 || response.status() === 403) {
    expect(response.status(), JSON.stringify(await safeJson(response))).toBe(201)
  }
}

async function createDepartment(api: any, input: { name: string; code: string; hrEmail: string }) {
  const response = await api.post('/api/departments', {
    data: {
      name: input.name,
      description: `${input.name} for payroll data preparation`,
    },
  })
  if (response.status() !== 201 && dbPatchEnabled()) {
    return createDepartmentInDb(
      input.hrEmail,
      input.code,
      input.name,
      `${input.name} for payroll data preparation`,
    )
  }
  expect(response.status(), JSON.stringify(await safeJson(response))).toBe(201)
  const payload: any = await safeJson(response)
  return payload?.data ?? payload?.message
}

async function createEmployee(api: any, input: {
  runId: string
  hrEmail: string
  email: string
  firstName: string
  lastName: string
  departmentCode: string
}) {
  const phone = uniquePhone()
  const response = await api.post('/api/v1/employees', {
    data: {
      email: input.email,
      firstName: input.firstName,
      lastName: input.lastName,
      departmentCode: input.departmentCode,
      roleCode: 'EMPLOYEE',
      gender: 'MALE',
      phone,
    },
  })
  if (response.status() !== 201 && dbPatchEnabled()) {
    const userProfileCode = createEmployeeInDb({
      hrEmail: input.hrEmail,
      accountCode: `ACC-QA-${input.runId}`,
      userProfileCode: `USR-QA-${input.runId}`,
      email: input.email,
      firstName: input.firstName,
      lastName: input.lastName,
      departmentCode: input.departmentCode,
      phone,
    })
    return {
      code: userProfileCode,
      email: input.email,
    }
  }
  expect(response.status(), JSON.stringify(await safeJson(response))).toBe(201)
  const payload: any = await safeJson(response)
  const employee = payload?.data ?? payload
  return {
    code: String(employee?.code ?? ''),
    email: String(employee?.email ?? input.email),
  }
}

async function createSalaryComponents(api: any, runId: string) {
  const hrEmail = requireAccount('HUMAN_RESOURCES').email
  const response = await api.post('/api/salaries', {
    data: [
      { name: `QA Base Salary ${runId}`, calculateMethod: 'FIXED', isDeduct: false },
      { name: `QA Meal Allowance ${runId}`, calculateMethod: 'FIXED', isDeduct: false },
    ],
  })
  if (response.status() !== 201 && dbPatchEnabled()) {
    const baseCode = createSalaryInDb({
      hrEmail,
      salaryCode: `SAL-QA-${runId}-BASE`,
      name: `QA Base Salary ${runId}`,
      calculateMethod: 'FIXED',
      isDeduct: false,
    })
    const allowanceCode = createSalaryInDb({
      hrEmail,
      salaryCode: `SAL-QA-${runId}-ALLOW`,
      name: `QA Meal Allowance ${runId}`,
      calculateMethod: 'FIXED',
      isDeduct: false,
    })
    return [
      { code: baseCode, name: `QA Base Salary ${runId}`, calculateMethod: 'FIXED' },
      { code: allowanceCode, name: `QA Meal Allowance ${runId}`, calculateMethod: 'FIXED' },
    ]
  }
  expect(response.status(), JSON.stringify(await safeJson(response))).toBe(201)
  const payload: any = await safeJson(response)
  return payload.map((item: any) => ({
    code: String(item.code),
    name: String(item.name),
    calculateMethod: String(item.calculateMethod),
  }))
}

